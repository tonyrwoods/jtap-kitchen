// HTML-escape user-controlled strings before interpolating them into HTML
// email bodies. Prevents HTML injection / content spoofing in transactional emails.
export function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}